"""Extract Iai MBD transition data from the user's local World installation.

Layout reference: Synthlight/MHW-Editor, 010 Templates/mbd.bt (version21).
Native1c007f0 selects a target entry, then a previous-motion override; native
1c014f0 retains its interpolation unless the action supplies an override.
"""
import json,struct
from animation_port import PROJECT,WORLD,sha
from compile_world_motion_links import read_mbd

def main():
    source=WORLD.with_suffix('.mbd');entries=read_mbd(source)
    selected={i:entries[i] for i in range(306,313)}
    for entry in selected.values():
        assert entry['rows'][0]['bank']=='Default'
        for row in entry['rows']:
            assert row['start']==0 and row['overlap']==10 and row['speed']==1 and row['modifier']==0
    report={'source':str(source),'sha256':sha(source),'entries':selected,
            'reference':'https://github.com/Synthlight/MHW-Editor/blob/master/010%20Templates/mbd.bt',
            'native_lookup_rva':'1c007f0','native_apply_rva':'1c014f0',
            'scope':'Iai entry interpolation only; GU interpolates from its current evaluated pose. World overlap-layer implementation is not claimed identical.'}
    (PROJECT/'research/world_blend.json').write_text(json.dumps(report,indent=2)+'\n')
    lines=['/* Generated by inspect_world_blend.py; source MBD v21. */',
           'static float world_iai_blend(unsigned target,unsigned previous,float frame)', '{','    switch(target){']
    for target,entry in selected.items():
        lines.append('    case %d:'%target)
        for row in entry['rows'][1:]:
            assert row['bank']=='w03_00'
            condition='previous==%du'%row['previous']
            if row['previous_frame_limit']>0:condition+='&&frame<=%ff'%row['previous_frame_limit']
            lines.append('        if(%s)return %ff;'%(condition,row['interpolation']))
        lines.append('        return %ff;'%entry['rows'][0]['interpolation'])
    lines+=['    default:return 0;','    }','}','']
    (PROJECT/'c/world_blend.h').write_text('\n'.join(lines),encoding='ascii')
    print('Extracted',len(selected),'Iai MBD entries;',sha(source))

if __name__=='__main__':main()
